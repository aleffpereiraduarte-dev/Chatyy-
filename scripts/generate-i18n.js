// Generate individual .js files
const i18nDir = path.join(__dirname, '..', 'i18n');

let generated = 0;
for (const [code, trans] of Object.entries(TRANSLATIONS)) {
  const filePath = path.join(i18nDir, `${code}.js`);
  // Skip if file already exists and is large (manually written)
  if (fs.existsSync(filePath)) {
    const stat = fs.statSync(filePath);
    if (stat.size > 50000) {
      console.log(`SKIP ${code} (already exists, ${stat.size} bytes)`);
      continue;
    }
  }

  const lines = ['export default {'];
  for (const [key, value] of Object.entries(trans)) {
    const escaped = typeof value === 'string' ? value.replace(/'/g, "\\'") : value;
    lines.push(`  '${key}': '${escaped}',`);
  }
  lines.push('};');
  lines.push('');

  fs.writeFileSync(filePath, lines.join('\n'), 'utf8');
  generated++;
  console.log(`OK ${code} (${Object.keys(trans).length} keys)`);
}

console.log(`\nGenerated ${generated} language files.`);
