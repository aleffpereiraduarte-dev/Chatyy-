const EXT_NAME = 'ChatyyCallActivity';
const EXT_BUNDLE_ID = 'com.onemundo.mail.CallActivity';
const DEPLOYMENT_TARGET = '16.1'; // ActivityKit minimum
const TEAM_ID = 'XN9XN27QCE';

function liveActivityGate() {
  const v = (process.env.CHATYY_LIVE_ACTIVITY || '').trim().toLowerCase();
  if (v === '1' || v === 'true' || v === 'on') return { on: true, why: 'CHATYY_LIVE_ACTIVITY=1' };
  return {
    on: false,
    why: `CHATYY_LIVE_ACTIVITY!=1 (needs provisioning for ${EXT_BUNDLE_ID} — scripts/asc-create-liveactivity-profile.js)`,
  };
}

