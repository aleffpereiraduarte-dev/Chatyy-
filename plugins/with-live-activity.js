/**
 * Config plugin — [2026-10-07 ios-native] Live Activity / Dynamic Island for an
 * ongoing call ("Em ligação com Fulano · 03:12").
 *
 * Adds the ChatyyCallActivity iOS target (WidgetKit extension hosting an
 * ActivityKit `ActivityConfiguration`) and `NSSupportsLiveActivities` on the
 * app. [2026-10-09] The same extension also hosts the large-upload Live
 * Activity (ChatyyUploadAttributes, app side in
 * modules/expo-background-upload/ios/UploadLiveActivity.swift) — no extra
 * bundle id / profile. The app side (start/end) lives in
 * modules/expo-callkit/ios/CallLiveActivity.swift and is called from
 * CallViewController when the call flips to "Conectado" / tears down. That
 * code is ALWAYS compiled but is a runtime no-op unless the app's Info.plist
 * has NSSupportsLiveActivities=true (i.e. this plugin ran) and the user
 * allows Live Activities.
 *
 * GATE — OFF by default (a new bundle id needs its own provisioning profile;
 * without it, manual-signing archive fails):
 *   CHATYY_LIVE_ACTIVITY=1   → ON   (set by the CI prebuild step when the
 *                                    IOS_PROFILE_LIVEACT_BASE64 secret exists,
 *                                    or by hand for local / EAS builds)
 *   anything else            → OFF  (plugin is a no-op, logs a notice)
 *
 * WHAT IT DOES (when ON):
 *   1. Writes ChatyyCallActivity.swift + Info.plist into
 *      ${platformProjectRoot}/ChatyyCallActivity/ (embedded strings below are
 *      canonical — ios/ is regenerated on every prebuild).
 *   2. PBXNativeTarget (app_extension, widgetkit-extension point) with bundle
 *      id com.onemundo.mail.CallActivity, deployment target 16.1, embedded in
 *      the Chatyy app + target dependency.
 *   3. Host Info.plist: NSSupportsLiveActivities = true.
 *   4. Signing: if LIVEACT_UUID / IOS_LIVEACT_PROFILE_UUID is in the env,
 *      the target is set to Manual with that profile (CI / Mac 207);
 *      otherwise Automatic (EAS cloud uses credentials.json
 *      `ios.ChatyyCallActivity`).
 *   No pods, no App Group, no entitlements: the widget only renders the
 *   ActivityKit state the app pushes locally.
 *
 * PROVISIONING (not done here — see scripts/asc-create-liveactivity-profile.js):
 *   bundle id com.onemundo.mail.CallActivity (no capabilities), App Store
 *   profile, GitHub secret IOS_PROFILE_LIVEACT_BASE64.
 *
 * KEEP IN SYNC: `ChatyyCallAttributes` below must match the struct in
 * modules/expo-callkit/ios/CallLiveActivity.swift field-for-field (ActivityKit
 * decodes the app's Codable state in the extension process by type name).
 */

