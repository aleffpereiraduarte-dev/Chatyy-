const WIDGET_SWIFT = `//
//  ChatyyWidgets.swift — generated by plugins/with-chatyy-widgets.js (edit it THERE).
//

import WidgetKit
import SwiftUI

private let chatyyAppGroup = "${APP_GROUP}"

struct ChatyyWidgetConv: Identifiable {
    let id: String
    let name: String
    let email: String
    let isGroup: Bool
    let pinned: Bool
    let unread: Int

    var url: URL {
        var c = URLComponents()
        c.scheme = "onemundomail"
        c.host = "chat-conversation"
        var q: [URLQueryItem] = [
            URLQueryItem(name: "id", value: id),
            URLQueryItem(name: "type", value: isGroup ? "group" : "direct"),
            URLQueryItem(name: "name", value: name),
        ]
        if !email.isEmpty { q.append(URLQueryItem(name: "email", value: email)) }
        q.append(URLQueryItem(name: "src", value: "widget"))
        c.queryItems = q
        return c.url ?? URL(string: "onemundomail://chat")!
    }

    var initial: String {
        let t = name.trimmingCharacters(in: .whitespacesAndNewlines)
        if let ch = t.first(where: { $0.isLetter || $0.isNumber }) { return String(ch).uppercased() }
        return "C"
    }
}

struct ChatyyWidgetEntry: TimelineEntry {
    let date: Date
    let items: [ChatyyWidgetConv]
    let locked: Bool
    let totalUnread: Int
}

enum ChatyyWidgetStore {
    static func load() -> ChatyyWidgetEntry {
        guard let ud = UserDefaults(suiteName: chatyyAppGroup) else {
            return ChatyyWidgetEntry(date: Date(), items: [], locked: false, totalUnread: 0)
        }
        let locked = ud.bool(forKey: "chatyy.widget_locked")
        var items: [ChatyyWidgetConv] = []
        if let data = ud.data(forKey: "chatyy.system_conversations"),
           let arr = (try? JSONSerialization.jsonObject(with: data, options: [])) as? [[String: Any]] {
            for d in arr {
                let id = (d["id"] as? String) ?? ""
                if id.isEmpty { continue }
                let name = (d["name"] as? String) ?? ""
                let email = (d["email"] as? String) ?? ""
                items.append(ChatyyWidgetConv(
                    id: id,
                    name: name.isEmpty ? (email.isEmpty ? "Chatyy" : email) : name,
                    email: email,
                    isGroup: ((d["type"] as? String) ?? "") == "group",
                    pinned: (d["pinned"] as? Bool) ?? false,
                    unread: (d["unread"] as? NSNumber)?.intValue ?? 0
                ))
            }
        }
        let ordered = items.filter { $0.pinned } + items.filter { !$0.pinned }
        let total = items.reduce(0) { $0 + max(0, $1.unread) }
        return ChatyyWidgetEntry(date: Date(), items: ordered, locked: locked, totalUnread: total)
    }
}

struct ChatyyConvProvider: TimelineProvider {
    func placeholder(in context: Context) -> ChatyyWidgetEntry {
        ChatyyWidgetEntry(date: Date(), items: [
            ChatyyWidgetConv(id: "1", name: "Ana", email: "", isGroup: false, pinned: true, unread: 2),
            ChatyyWidgetConv(id: "2", name: "Família", email: "", isGroup: true, pinned: false, unread: 0),
        ], locked: false, totalUnread: 2)
    }

    func getSnapshot(in context: Context, completion: @escaping (ChatyyWidgetEntry) -> Void) {
        completion(context.isPreview ? placeholder(in: context) : ChatyyWidgetStore.load())
    }

    func getTimeline(in context: Context, completion: @escaping (Timeline<ChatyyWidgetEntry>) -> Void) {
        // The app pushes reloads on every list change; this is only a safety net.
        let entry = ChatyyWidgetStore.load()
        completion(Timeline(entries: [entry], policy: .after(Date().addingTimeInterval(30 * 60))))
    }
}

private struct ChatyyWidgetBackground: ViewModifier {
    func body(content: Content) -> some View {
        if #available(iOS 17.0, *) {
            content.containerBackground(for: .widget) { Color(.systemBackground) }
        } else {
            content.padding(12).background(Color(.systemBackground))
        }
    }
}

private struct ChatyyAvatar: View {
    let conv: ChatyyWidgetConv
    var size: CGFloat = 30
    var body: some View {
        ZStack {
            Circle().fill(Color.primary)
            Text(conv.initial)
                .font(.system(size: size * 0.44, weight: .bold))
                .foregroundColor(Color(.systemBackground))
        }
        .frame(width: size, height: size)
    }
}

private struct ChatyyUnreadBadge: View {
    let count: Int
    var body: some View {
        Text(verbatim: count > 99 ? "99+" : "\\(count)")
            .font(.system(size: 11, weight: .bold))
            .foregroundColor(Color(.systemBackground))
            .padding(.horizontal, 6)
            .frame(minWidth: 20, minHeight: 20)
            .background(Capsule().fill(Color.primary))
    }
}

private struct ChatyyRow: View {
    let conv: ChatyyWidgetConv
    var body: some View {
        HStack(spacing: 10) {
            ChatyyAvatar(conv: conv)
            Text(conv.name)
                .font(.system(size: 14, weight: conv.unread > 0 ? .semibold : .regular))
                .foregroundColor(.primary)
                .lineLimit(1)
            Spacer(minLength: 4)
            if conv.unread > 0 { ChatyyUnreadBadge(count: conv.unread) }
        }
    }
}

struct ChatyyConversationsView: View {
    @Environment(\\.widgetFamily) var family
    let entry: ChatyyWidgetEntry

    var body: some View {
        switch family {
        case .accessoryCircular:
            ZStack {
                AccessoryWidgetBackground()
                VStack(spacing: 0) {
                    Image(systemName: "bubble.left.and.bubble.right.fill").font(.system(size: 12))
                    Text(verbatim: entry.locked ? "-" : "\\(entry.totalUnread)").font(.system(size: 16, weight: .bold))
                }
            }
            .widgetURL(URL(string: "onemundomail://chat"))
        case .accessoryRectangular:
            VStack(alignment: .leading, spacing: 2) {
                Text("Chatyy").font(.headline)
                if entry.locked || entry.items.isEmpty {
                    Text(verbatim: entry.locked ? "Chatyy" : "-").font(.caption)
                } else {
                    ForEach(entry.items.prefix(2)) { c in
                        Text(verbatim: c.unread > 0 ? "\\(c.name) · \\(c.unread)" : c.name).font(.caption).lineLimit(1)
                    }
                }
            }
            .widgetURL(URL(string: "onemundomail://chat"))
        case .systemSmall:
            smallBody.modifier(ChatyyWidgetBackground())
        default:
            mediumBody.modifier(ChatyyWidgetBackground())
        }
    }

    private var header: some View {
        HStack {
            Text("Chatyy").font(.system(size: 16, weight: .bold)).foregroundColor(.primary)
            Spacer()
            Link(destination: URL(string: "onemundomail://chat-new")!) {
                Image(systemName: "square.and.pencil").foregroundColor(.primary)
            }
        }
    }

    private var smallBody: some View {
        VStack(alignment: .leading, spacing: 8) {
            Text("Chatyy").font(.system(size: 16, weight: .bold))
            if entry.locked || entry.items.isEmpty {
                Spacer()
            } else {
                ForEach(entry.items.prefix(3)) { c in
                    HStack(spacing: 6) {
                        ChatyyAvatar(conv: c, size: 22)
                        Text(c.name).font(.system(size: 12)).lineLimit(1)
                        Spacer(minLength: 0)
                        if c.unread > 0 { Circle().fill(Color.primary).frame(width: 7, height: 7) }
                    }
                }
                Spacer(minLength: 0)
            }
        }
        .widgetURL(entry.items.first.map { $0.url } ?? URL(string: "onemundomail://chat"))
    }

    private var mediumBody: some View {
        VStack(alignment: .leading, spacing: 6) {
            header
            if entry.locked || entry.items.isEmpty {
                Spacer()
            } else {
                ForEach(entry.items.prefix(4)) { c in
                    Link(destination: c.url) { ChatyyRow(conv: c) }
                }
                Spacer(minLength: 0)
            }
        }
    }
}

struct ChatyyConversationsWidget: Widget {
    let kind = "ChatyyConversations"
    var body: some WidgetConfiguration {
        StaticConfiguration(kind: kind, provider: ChatyyConvProvider()) { entry in
            ChatyyConversationsView(entry: entry)
        }
        .configurationDisplayName("Chatyy")
        .description("Recent and pinned chats")
        .supportedFamilies([.systemSmall, .systemMedium, .accessoryCircular, .accessoryRectangular])
    }
}

@main
struct ChatyyWidgetsBundle: WidgetBundle {
    var body: some Widget {
        ChatyyConversationsWidget()
    }
}
`;

const EMBEDDED_FILES = {
  'ChatyyWidgets.swift': WIDGET_SWIFT,
  'Info.plist': INFO_PLIST,
  [`${EXT_NAME}.entitlements`]: ENTITLEMENTS,
};

function withWidgetFiles(config) {
  return withDangerousMod(config, ['ios', async (cfg) => {
    const destDir = path.join(cfg.modRequest.platformProjectRoot, EXT_NAME);
    if (!fs.existsSync(destDir)) fs.mkdirSync(destDir, { recursive: true });
    for (const [fileName, content] of Object.entries(EMBEDDED_FILES)) {
      fs.writeFileSync(path.join(destDir, fileName), content, 'utf8');
    }
    return cfg;
  }]);
}

function withMainAppGroup(config) {
  return withEntitlementsPlist(config, (cfg) => {
    const groups = cfg.modResults['com.apple.security.application-groups'] || [];
    if (!groups.includes(APP_GROUP)) groups.push(APP_GROUP);
    cfg.modResults['com.apple.security.application-groups'] = groups;
    return cfg;
  });
}

function withWidgetTarget(config) {
  return withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const projObjects = project.hash.project.objects;
    projObjects.PBXTargetDependency = projObjects.PBXTargetDependency || {};
    projObjects.PBXContainerItemProxy = projObjects.PBXContainerItemProxy || {};

    const existing = project.pbxNativeTargetSection?.() || {};
    for (const key of Object.keys(existing)) {
      const t = existing[key];
      if (t && typeof t === 'object' && (t.name === EXT_NAME || t.name === `"${EXT_NAME}"`)) return cfg;
    }

    const group = project.addPbxGroup(['ChatyyWidgets.swift', 'Info.plist', `${EXT_NAME}.entitlements`], EXT_NAME, EXT_NAME, '"<group>"');
    const rootGroup = project.getFirstProject().firstProject.mainGroup;
    project.addToPbxGroup(group.uuid, rootGroup);

    const target = project.addTarget(EXT_NAME, 'app_extension', EXT_NAME, EXT_BUNDLE_ID);
    project.addBuildPhase(['ChatyyWidgets.swift'], 'PBXSourcesBuildPhase', 'Sources', target.uuid);
    project.addBuildPhase([], 'PBXFrameworksBuildPhase', 'Frameworks', target.uuid);
    project.addBuildPhase([], 'PBXResourcesBuildPhase', 'Resources', target.uuid);

    let mainAppTargetUuid = null;
    const nativeTargets = project.pbxNativeTargetSection() || {};
    for (const key of Object.keys(nativeTargets)) {
      const t = nativeTargets[key];
      if (t && typeof t === 'object' && t.productType === '"com.apple.product-type.application"') {
        const uuid = key.replace(/_comment$/, '');
        if (!/^[A-F0-9]+$/i.test(uuid)) continue;
        mainAppTargetUuid = uuid;
        break;
      }
    }
    if (!mainAppTargetUuid) mainAppTargetUuid = project.getFirstTarget().uuid;
    project.addBuildPhase([], 'PBXCopyFilesBuildPhase', 'Embed App Extensions', mainAppTargetUuid, 'app_extension');
    try {
      project.addTargetDependency(mainAppTargetUuid, [target.uuid]);
    } catch (e) {
      console.warn('[with-chatyy-widgets] addTargetDependency failed:', e?.message || e);
    }

    const marketingVersion = cfg.version ? `${cfg.version}` : '1.0';
    const projectVersion = (cfg.ios && cfg.ios.buildNumber) ? `${cfg.ios.buildNumber}` : '1';
    const profile = process.env.WIDGETS_UUID || process.env.IOS_WIDGETS_PROFILE_UUID || '';

    const xcConfig = project.pbxXCBuildConfigurationSection();
    for (const key of Object.keys(xcConfig)) {
      const c = xcConfig[key];
      if (!c || !c.buildSettings || c.buildSettings.PRODUCT_NAME !== `"${EXT_NAME}"`) continue;
      const s = c.buildSettings;
      s.INFOPLIST_FILE = `"${EXT_NAME}/Info.plist"`;
      s.CODE_SIGN_ENTITLEMENTS = `"${EXT_NAME}/${EXT_NAME}.entitlements"`;
      s.IPHONEOS_DEPLOYMENT_TARGET = `"${DEPLOYMENT_TARGET}"`;
      s.SWIFT_VERSION = '5.0';
      s.PRODUCT_BUNDLE_IDENTIFIER = `"${EXT_BUNDLE_ID}"`;
      s.TARGETED_DEVICE_FAMILY = '"1,2"';
      s.MARKETING_VERSION = `"${marketingVersion}"`;
      s.CURRENT_PROJECT_VERSION = `"${projectVersion}"`;
      s.SKIP_INSTALL = 'YES';
      s.APPLICATION_EXTENSION_API_ONLY = 'YES';
      s.GENERATE_INFOPLIST_FILE = 'NO';
      s.ASSETCATALOG_COMPILER_GLOBAL_ACCENT_COLOR_NAME = '""';
      s.ASSETCATALOG_COMPILER_WIDGET_BACKGROUND_COLOR_NAME = '""';
      s.LD_RUNPATH_SEARCH_PATHS = '"$(inherited) @executable_path/Frameworks @executable_path/../../Frameworks"';
      if (profile) {
        s.CODE_SIGN_STYLE = 'Manual';
        s.DEVELOPMENT_TEAM = TEAM_ID;
        s.CODE_SIGN_IDENTITY = '"Apple Distribution"';
        s['"CODE_SIGN_IDENTITY[sdk=iphoneos*]"'] = '"Apple Distribution"';
        s.PROVISIONING_PROFILE_SPECIFIER = `"${profile}"`;
        s.PROVISIONING_PROFILE = `"${profile}"`;
      } else {
        s.CODE_SIGN_STYLE = '"Automatic"';
        s.DEVELOPMENT_TEAM = TEAM_ID;
      }
    }
    return cfg;
  });
}

module.exports = function withChatyyWidgets(config) {
  const gate = widgetsGate();
  if (!gate.on) {
    console.log(`[with-chatyy-widgets] OFF — ${gate.why}. No widget target.`);
    return config;
  }
  console.log(`[with-chatyy-widgets] ON — ${gate.why}`);
  config = withWidgetFiles(config);
  config = withMainAppGroup(config);
  config = withWidgetTarget(config);
  return config;
};

module.exports.EXT_NAME = EXT_NAME;
module.exports.EXT_BUNDLE_ID = EXT_BUNDLE_ID;
module.exports.widgetsGate = widgetsGate;
