/**
 * Config plugin — [2026-10-09 system-integration] iOS home-screen / lock-screen
 * widgets ("Conversas do Chatyy"): recent + pinned conversations with unread
 * counts (never message content). WidgetKit extension target ChatyyWidgets.
 *
 * Data: App Group group.com.onemundo.mail, key chatyy.system_conversations
 * (+ chatyy.widget_locked), written by ExpoChatyySystem.setConversations
 * (modules/expo-native-toolkit/ios/ExpoChatyySystemModule.swift), which also
 * calls WidgetCenter.reloadAllTimelines().
 * Taps: onemundomail://chat-conversation?id=… (expo-router deep link).
 *
 * GATE — OFF by default (new bundle id needs its own provisioning profile with
 * the App Group; without it a manual-signing archive fails):
 *   CHATYY_WIDGETS=1 → ON   (set by CI when IOS_PROFILE_WIDGETS_BASE64 exists,
 *                            or by hand for local / EAS builds)
 *   anything else    → OFF
 *
 * WHAT IT DOES (when ON):
 *   1. Writes ChatyyWidgets.swift + Info.plist + ChatyyWidgets.entitlements into
 *      ${platformProjectRoot}/ChatyyWidgets/.
 *   2. PBXNativeTarget (app_extension, widgetkit-extension point), bundle id
 *      com.onemundo.mail.Widgets, deployment target 16.0, embedded in the app.
 *   3. Signing: WIDGETS_UUID / IOS_WIDGETS_PROFILE_UUID in env → Manual with
 *      that profile; otherwise Automatic.
 *
 * PROVISIONING (not done here — scripts/asc-create-widgets-profile.js):
 *   bundle id com.onemundo.mail.Widgets + APP_GROUPS capability linked to
 *   group.com.onemundo.mail, App Store profile, GitHub secret
 *   IOS_PROFILE_WIDGETS_BASE64 (+ credentials.json ios.ChatyyWidgets for EAS).
 */
const fs = require('fs');
const path = require('path');
const { withXcodeProject, withDangerousMod, withEntitlementsPlist } = require('expo/config-plugins');

const EXT_NAME = 'ChatyyWidgets';
const EXT_BUNDLE_ID = 'com.onemundo.mail.Widgets';
const APP_GROUP = 'group.com.onemundo.mail';
const DEPLOYMENT_TARGET = '16.0';
const TEAM_ID = 'XN9XN27QCE';

function widgetsGate() {
  const v = (process.env.CHATYY_WIDGETS || '').trim().toLowerCase();
  if (v === '1' || v === 'true' || v === 'on') return { on: true, why: 'CHATYY_WIDGETS=1' };
  return { on: false, why: `CHATYY_WIDGETS!=1 (needs provisioning for ${EXT_BUNDLE_ID} — scripts/asc-create-widgets-profile.js)` };
}

