/**
 * [2026-10-09 system-integration] iOS App Intents (Siri / Atalhos / Spotlight)
 * + Focus filter (SetFocusFilterIntent) compiled into the MAIN app target.
 *
 * WHY THE MAIN TARGET: App Intents metadata (Metadata.appintents) is only
 * extracted for the target that compiles the intent types. Intents living in
 * a static CocoaPod (modules/expo-native-toolkit) are NOT discovered by Siri.
 *
 * WHAT IT DOES (every prebuild — ios/ is regenerated):
 *   1. Writes ios/<Project>/ChatyyAppIntents.swift (embedded below) and adds it
 *      to the app target's Sources.
 *   2. Writes AppShortcuts.xcstrings (Siri phrases) + Localizable.xcstrings
 *      (titles/dialogs) — pt-BR / pt-PT / es / en — as app Resources, and adds
 *      those regions to the project's knownRegions.
 *   3. NSUserActivityTypes += INStartCallIntent / INStartAudioCallIntent /
 *      INStartVideoCallIntent (Phone app Recents → "Chatyy" call-back lands in
 *      AppShortcutsAppDelegateSubscriber.continueUserActivity).
 *
 * NO new capability / provisioning: App Intents + App Shortcuts + Focus
 * filters need no Siri entitlement (that is only for legacy SiriKit intents).
 * Data comes from the App Group the app already has (group.com.onemundo.mail):
 *   chatyy.system_conversations (written by ExpoChatyySystem.setConversations)
 *   chatyy.recent_conversations (legacy ShareExtension snapshot — fallback)
 *   chatyy.auth_token / chatyy.base_url (ShareExtension bridge)
 *
 * Launch routing: intents that open the app park the onemundomail:// URL in
 * UserDefaults + post "ChatyyIntentOpenURL"; ChatyyShortcutCenter
 * (modules/expo-native-toolkit/ios/ExpoAppShortcutsModule.swift) delivers it to
 * JS through the SAME path the home-screen quick actions use.
 *
 * GATE: CHATYY_APP_INTENTS=0 disables everything (emergency switch).
 */
