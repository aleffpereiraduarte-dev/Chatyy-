function withIntentFiles(config) {
  return withDangerousMod(config, ['ios', async (cfg) => {
    const dir = path.join(cfg.modRequest.platformProjectRoot, cfg.modRequest.projectName);
    if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, SWIFT_FILE), SWIFT, 'utf8');
    fs.writeFileSync(path.join(dir, PHRASES_FILE), catalog(PHRASES), 'utf8');
    fs.writeFileSync(path.join(dir, STRINGS_FILE), catalog(STRINGS), 'utf8');
    return cfg;
  }]);
}

function withIntentActivityTypes(config) {
  return withInfoPlist(config, (cfg) => {
    const cur = Array.isArray(cfg.modResults.NSUserActivityTypes) ? cfg.modResults.NSUserActivityTypes : [];
    const want = ['INSendMessageIntent', 'INStartCallIntent', 'INStartAudioCallIntent', 'INStartVideoCallIntent'];
    cfg.modResults.NSUserActivityTypes = Array.from(new Set([...cur, ...want]));
    return cfg;
  });
}

function hasFileRef(project, basename) {
  const refs = project.pbxFileReferenceSection();
  for (const k of Object.keys(refs)) {
    const r = refs[k];
    if (r && typeof r === 'object' && (r.name === basename || r.name === `"${basename}"`
      || r.path === basename || r.path === `"${basename}"`
      || String(r.path || '').replace(/"/g, '').endsWith('/' + basename))) return true;
  }
  return false;
}

function withIntentXcode(config) {
  return withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const projectName = cfg.modRequest.projectName;
    const XU = IOSConfig.XcodeUtils;

    if (!hasFileRef(project, SWIFT_FILE)) {
      XU.addBuildSourceFileToGroup({ filepath: path.join(projectName, SWIFT_FILE), groupName: projectName, project });
    }
    for (const f of [PHRASES_FILE, STRINGS_FILE]) {
      if (hasFileRef(project, f)) continue;
      XU.addResourceFileToGroup({ filepath: path.join(projectName, f), groupName: projectName, project, isBuildFile: true });
    }
    // The xcode npm lib doesn't know .xcstrings → fix the file type so Xcode
    // compiles the catalog into <lang>.lproj/*.strings instead of copying it.
    const refs = project.pbxFileReferenceSection();
    for (const k of Object.keys(refs)) {
      const r = refs[k];
      if (!r || typeof r !== 'object') continue;
      const p = String(r.path || r.name || '').replace(/"/g, '');
      if (p.endsWith('.xcstrings')) {
        r.lastKnownFileType = 'text.json.xcstrings';
        delete r.explicitFileType;
      }
    }
    // knownRegions += pt-BR, pt-PT, es (localized phrases need them).
    const projects = project.hash.project.objects.PBXProject || {};
    for (const k of Object.keys(projects)) {
      const p = projects[k];
      if (!p || typeof p !== 'object' || !Array.isArray(p.knownRegions)) continue;
      const have = new Set(p.knownRegions.map((x) => String(x).replace(/"/g, '')));
      for (const l of LANGS) if (!have.has(l)) p.knownRegions.push(l.includes('-') ? `"${l}"` : l);
    }
    return cfg;
  });
}

module.exports = function withSystemIntents(config) {
  if (!gateOn()) {
    console.log('[with-system-intents] OFF (CHATYY_APP_INTENTS=0)');
    return config;
  }
  config = withIntentFiles(config);
  config = withIntentActivityTypes(config);
  config = withIntentXcode(config);
  return config;
};

