function unit(v) { return { stringUnit: { state: 'translated', value: v } }; }
function catalog(entries) {
  const strings = {};
  for (const [key, tr] of Object.entries(entries)) {
    const loc = {};
    for (const l of LANGS) if (tr[l]) loc[l] = unit(tr[l]);
    strings[key] = { extractionState: 'manual', localizations: loc };
  }
  return JSON.stringify({ sourceLanguage: 'en', strings, version: '1.0' }, null, 2) + '\n';
}

