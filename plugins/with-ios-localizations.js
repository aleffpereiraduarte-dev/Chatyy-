/**
 * [2026-10-12 native-polish] iOS localization parity with Android
 * (plugins/with-android-native-polish.js already ships android:localeConfig).
 *
 * Before this the app bundle had NO localization at all (only the English
 * Info.plist), so on a pt-BR iPhone:
 *   - every permission prompt (camera, mic, contacts, photos, Face ID...) was
 *     in ENGLISH;
 *   - system UI hosted by the app (share sheet / context-menu / photo picker /
 *     date picker labels, "Cancel", etc.) fell back to English;
 *   - Settings > Chatyy had no "Language" row (iOS per-app language).
 *
 * What it does (ios/ is regenerated by `expo prebuild --clean` in CI):
 *   1. CFBundleLocalizations = every locale LanguageContext can render
 *      (i18n/manifest.json, same source as the Android locales_config), mapped
 *      to Apple codes (zh-CN -> zh-Hans). Enables the per-app language picker
 *      and localized system UI. LanguageContext reads AppleLanguages, which iOS
 *      sets to the per-app choice, so the JS side follows automatically; a
 *      manual in-app choice still wins (unchanged precedence). RTL stays owned
 *      by LanguageContext (allowRTL/forceRTL keyed to the APP language).
 *   2. <lang>.lproj/InfoPlist.strings with translated permission prompts
 *      (plugins/ios-infoplist-strings.json) as ONE PBXVariantGroup in the app
 *      target Resources (same pattern as with-system-intents.js). Keys missing
 *      for a language fall back to the English Info.plist value.
 *
 * No Swift, no capability, no new dependency. Opt-out: CHATYY_IOS_L10N=0.
 */
const fs = require('fs');
const path = require('path');
const { withDangerousMod, withInfoPlist, withXcodeProject, IOSConfig } = require('@expo/config-plugins');

const STRINGS_FILE = 'InfoPlist.strings';
const DATA_FILE = path.join(__dirname, 'ios-infoplist-strings.json');
// i18n code -> Apple localization code (only where they differ).
const APPLE_CODE = { 'zh-CN': 'zh-Hans' };

function gateOn() {
  const v = String(process.env.CHATYY_IOS_L10N || '').trim().toLowerCase();
  return !(v === '0' || v === 'false' || v === 'off');
}

function readLocales(projectRoot) {
  const out = [];
  try {
    const m = JSON.parse(fs.readFileSync(path.join(projectRoot, 'i18n', 'manifest.json'), 'utf8'));
    for (const l of m.core || []) out.push(l);
    for (const l of Object.keys(m.locales || {})) out.push(l);
  } catch (e) {
    out.push('pt-BR', 'en', 'es', 'pt-PT');
  }
  const mapped = out
    .filter((x) => /^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$/.test(x))
    .map((x) => APPLE_CODE[x] || x);
  // 'en' first = development region (base Info.plist strings are English).
  return [...new Set(['en', ...mapped])];
}

function readStrings() {
  try {
    const raw = JSON.parse(fs.readFileSync(DATA_FILE, 'utf8'));
    const out = {};
    for (const [lang, map] of Object.entries(raw)) {
      if (lang.startsWith('_') || !map || typeof map !== 'object') continue;
      const clean = {};
      for (const [k, v] of Object.entries(map)) {
        if (/^NS[A-Za-z]+UsageDescription$/.test(k) && typeof v === 'string' && v.trim()) clean[k] = v;
      }
      if (Object.keys(clean).length) out[APPLE_CODE[lang] || lang] = clean;
    }
    return out;
  } catch (e) {
    console.warn('[with-ios-localizations] could not read ' + DATA_FILE + ': ' + e.message);
    return {};
  }
}

// .strings value escaping (UTF-8 file; Xcode converts to binary at build).
function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, '\\n');
}

function withL10nInfoPlist(config) {
  return withInfoPlist(config, (cfg) => {
    cfg.modResults.CFBundleLocalizations = readLocales(cfg.modRequest.projectRoot);
    return cfg;
  });
}

function withL10nFiles(config) {
  return withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, cfg.modRequest.projectName);
      const data = readStrings();
      for (const [lang, map] of Object.entries(data)) {
        const ld = path.join(dir, `${lang}.lproj`);
        fs.mkdirSync(ld, { recursive: true });
        const body = Object.entries(map).map(([k, v]) => `"${k}" = "${esc(v)}";`).join('\n') + '\n';
        fs.writeFileSync(path.join(ld, STRINGS_FILE), body, 'utf8');
      }
      return cfg;
    },
  ]);
}

const unq = (v) => String(v == null ? '' : v).replace(/"/g, '');

// <lang>.lproj/InfoPlist.strings as ONE PBXVariantGroup (what Xcode creates on
// "Localize..."), one PBXBuildFile in the app target's Resources. Idempotent.
function addLocalizedVariantGroup(project, projectName, fileName, langs) {
  const objects = project.hash.project.objects;
  objects.PBXVariantGroup = objects.PBXVariantGroup || {};
  const vgs = objects.PBXVariantGroup;
  let vgKey = Object.keys(vgs).find((k) => !k.endsWith('_comment') && vgs[k] && unq(vgs[k].name) === fileName);
  if (!vgKey) {
    vgKey = project.generateUuid();
    vgs[vgKey] = { isa: 'PBXVariantGroup', children: [], name: fileName, sourceTree: '"<group>"' };
    vgs[`${vgKey}_comment`] = fileName;
    const group = IOSConfig.XcodeUtils.ensureGroupRecursively(project, projectName);
    if (group && Array.isArray(group.children) && !group.children.some((c) => c.value === vgKey)) {
      group.children.push({ value: vgKey, comment: fileName });
    }
    const target = IOSConfig.XcodeUtils.getApplicationNativeTarget({ project, projectName });
    const phase = project.pbxResourcesBuildPhaseObj(target.uuid);
    if (!phase) throw new Error('[with-ios-localizations] app target has no Resources build phase');
    const bfKey = project.generateUuid();
    objects.PBXBuildFile[bfKey] = { isa: 'PBXBuildFile', fileRef: vgKey, fileRef_comment: fileName };
    objects.PBXBuildFile[`${bfKey}_comment`] = `${fileName} in Resources`;
    phase.files = phase.files || [];
    phase.files.push({ value: bfKey, comment: `${fileName} in Resources` });
  }
  const vg = vgs[vgKey];
  const refs = objects.PBXFileReference;
  const have = new Set((vg.children || []).map((c) => unq(refs[c.value] && refs[c.value].name)));
  for (const l of langs) {
    if (have.has(l)) continue;
    const refKey = project.generateUuid();
    refs[refKey] = {
      isa: 'PBXFileReference',
      lastKnownFileType: 'text.plist.strings',
      name: l.includes('-') ? `"${l}"` : l,
      path: `"${projectName}/${l}.lproj/${fileName}"`,
      sourceTree: '"<group>"',
    };
    refs[`${refKey}_comment`] = l;
    vg.children.push({ value: refKey, comment: l });
  }
}

function withL10nXcode(config) {
  return withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const projectName = cfg.modRequest.projectName;
    const langs = Object.keys(readStrings());
    if (langs.length) addLocalizedVariantGroup(project, projectName, STRINGS_FILE, langs);
    // knownRegions += every bundled localization (silences Xcode's
    // "unknown region" warning; harmless if already present).
    const regions = [...new Set([...readLocales(cfg.modRequest.projectRoot), ...langs])];
    const projects = project.hash.project.objects.PBXProject || {};
    for (const k of Object.keys(projects)) {
      const p = projects[k];
      if (!p || typeof p !== 'object' || !Array.isArray(p.knownRegions)) continue;
      const have = new Set(p.knownRegions.map((x) => unq(x)));
      for (const l of regions) if (!have.has(l)) p.knownRegions.push(l.includes('-') ? `"${l}"` : l);
    }
    return cfg;
  });
}

module.exports = function withIosLocalizations(config) {
  if (!gateOn()) {
    console.log('[with-ios-localizations] OFF (CHATYY_IOS_L10N=0)');
    return config;
  }
  config = withL10nInfoPlist(config);
  config = withL10nFiles(config);
  config = withL10nXcode(config);
  return config;
};
